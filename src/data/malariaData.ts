// Helper to generate sample records
const makeSamples = (pattern: "res" | "mix" | "wild" | "het", refAd = 40, altAd = 50) => {
  const result: Variant["samples"] = {};
  SAMPLES.forEach((s) => {
    const isKL = s.startsWith("KL_");
    const isAS = s.startsWith("AS_");

    if (pattern === "res") {
      if (isKL) {
        result[s] = { GT: "1/1", DP: 68 + (s.charCodeAt(5) % 15), AD: `2,${66 + (s.charCodeAt(5) % 15)}`, GQ: 99 };
      } else if (isAS) {
        result[s] = s.endsWith("2") || s.endsWith("4")
          ? { GT: "0/1", DP: 48, AD: "23,25", GQ: 78 }
          : { GT: "0/0", DP: 42, AD: "41,1", GQ: 99 };
      } else {
        result[s] = s.endsWith("1") || s.endsWith("4")
          ? { GT: "1/1", DP: 60, AD: "2,58", GQ: 99 }
          : s.endsWith("2") ? { GT: "0/1", DP: 55, AD: "26,29", GQ: 82 } : { GT: "0/0", DP: 45, AD: "44,1", GQ: 98 };
      }
    } else if (pattern === "het") {
      result[s] = isKL
        ? { GT: "0/1", DP: 72, AD: "34,38", GQ: 84 }
        : { GT: "0/0", DP: 40, AD: "39,1", GQ: 98 };
    } else if (pattern === "mix") {
      result[s] = isKL
        ? { GT: "1/2", DP: 75, AD: "3,45,27", GQ: 88 }
        : { GT: "0/1", DP: 44, AD: "21,23", GQ: 76 };
    } else {
      result[s] = { GT: "0/0", DP: 48, AD: "47,1", GQ: 99 };
    }
  });
  return result;
};

